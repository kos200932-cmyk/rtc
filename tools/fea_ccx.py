#!/usr/bin/env python3
"""Preliminary check of the link strength data with CalculiX (free FE solver) - before Ansys.

    python tools/fea_ccx.py [--fea fea/RTC-7] [--only LINK-3] [--h-factor 1.0]

The same input as the Ansys scripts (rtc7_fea.json, geometry/*.step): gmsh tet10 mesh, the FIXED faces found by the
same vertex rules -> all DOF fixed, the LOAD faces -> rigid body to the remote point with force + moment,
the part's acceleration field as GRAV; one step per load case. Out: max von Mises (whole part and away from the
support / load faces - the rigid fixing makes stress peaks at their edges), max displacement, the support
reaction force vs the expected one. Summary -> fea/RTC-7/ccx/summary.md (+ .csv).
"""
import argparse
import json
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fea_export as fe  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def mesh(step, h):
    import gmsh
    gmsh.initialize()
    gmsh.option.setNumber("General.Terminal", 0)
    gmsh.model.add("m")
    gmsh.model.occ.importShapes(step)
    gmsh.model.occ.synchronize()
    gmsh.option.setNumber("Mesh.MeshSizeMax", h)
    gmsh.option.setNumber("Mesh.MeshSizeMin", h * 0.3)
    gmsh.option.setNumber("Mesh.ElementOrder", 2)
    gmsh.option.setNumber("Mesh.HighOrderOptimize", 1)
    gmsh.model.mesh.generate(3)
    tags, xyz, _ = gmsh.model.mesh.getNodes()
    X = xyz.reshape(-1, 3)
    nid = {int(t): i for i, t in enumerate(tags)}
    et, etags, enodes = gmsh.model.mesh.getElements(3)
    k = list(et).index(11)                       # 11 = tet10
    E = np.array(enodes[k], dtype=np.int64).reshape(-1, 10)
    surf = {}
    for _, s in gmsh.model.getEntities(2):
        pts = gmsh.model.getBoundary([(2, s)], combined=False, oriented=False, recursive=True)
        V = np.array([gmsh.model.getValue(0, p[1], []) for p in pts if p[0] == 0])
        nt, _, _ = gmsh.model.mesh.getNodes(2, s, includeBoundary=True)
        surf[s] = (V, set(int(t) for t in nt))
    gmsh.finalize()
    return tags.astype(np.int64), X, E, surf, nid


def run(model, cfg, outdir, hfac):
    step = os.path.join(os.path.dirname(outdir), model["step"])
    h = model["mesh_mm"] * hfac
    tags, X, E, surf, nid = mesh(step, h)
    sets = {}
    for role in ("fixed", "load"):
        s = set()
        for tag, (V, nodes) in surf.items():
            if any(fe.match(sel, V) for sel in model[role]["selectors"]):
                s |= nodes
        if not s:
            raise SystemExit(f"{model['id']} {role}: no surfaces matched in the gmsh model")
        sets[role] = sorted(s)
    mat = cfg["material"]
    rp, rot = int(tags.max()) + 1, int(tags.max()) + 2
    c = model["load"]["center"]
    L = ["*HEADING", f"RTC-7 {model['id']} - generated by tools/fea_ccx.py", "*NODE"]
    L += [f"{int(t)},{x:.6f},{y:.6f},{z:.6f}" for t, (x, y, z) in zip(tags, X)]
    L += [f"{rp},{c[0]},{c[1]},{c[2]}", f"{rot},{c[0]},{c[1]},{c[2]}"]
    L.append("*ELEMENT,TYPE=C3D10,ELSET=EALL")
    for i, e in enumerate(E):
        e = e[[0, 1, 2, 3, 4, 5, 6, 7, 9, 8]]       # gmsh -> CalculiX node order (edges 1-3 / 2-3 swapped)
        L.append(f"{i + 1}," + ",".join(str(int(n)) for n in e))
    for role in ("fixed", "load"):
        L.append(f"*NSET,NSET=N{role.upper()}")
        ids = sets[role]
        L += [",".join(str(n) for n in ids[j:j + 12]) for j in range(0, len(ids), 12)]
    L += ["*MATERIAL,NAME=AMG6", "*ELASTIC", f"{mat['E_MPa']},{mat['nu']}", "*DENSITY", f"{mat['rho'] * 1e-12:.4e}",
          "*SOLID SECTION,ELSET=EALL,MATERIAL=AMG6",
          f"*RIGID BODY,NSET=NLOAD,REF NODE={rp},ROT NODE={rot}",
          "*BOUNDARY", "NFIXED,1,3,0.0"]
    for cs in model["cases"]:
        F, M, A = cs["F_N"], cs["M_Nmm"], np.array(cs["acc_mm_s2"])
        L += ["*STEP", "*STATIC" + (",SOLVER=ITERATIVE CHOLESKY" if len(tags) > 160000 else ""), "*CLOAD,OP=NEW"]
        for k in range(3):
            L += [f"{rp},{k + 1},{F[k]}", f"{rot},{k + 1},{M[k]}"]
        a = np.linalg.norm(A)
        L.append("*DLOAD,OP=NEW")
        if a > 1e-9:
            d = -A / a                                  # body force = -rho*A (Ansys acceleration convention)
            L.append(f"EALL,GRAV,{a:.4f},{d[0]:.6f},{d[1]:.6f},{d[2]:.6f}")
        L += ["*NODE FILE", "U", "*EL FILE", "S", "*NODE PRINT,NSET=NFIXED,TOTALS=ONLY", "RF", "*END STEP"]
    job = os.path.join(outdir, model["id"])
    open(job + ".inp", "w").write("\n".join(L) + "\n")
    r = subprocess.run(["ccx", "-i", job], cwd=outdir, capture_output=True, text=True,
                       env=dict(os.environ, OMP_NUM_THREADS="4"))
    if not os.path.isfile(job + ".frd") or os.path.getsize(job + ".frd") < 1000:
        raise SystemExit(f"{model['id']}: CalculiX failed\n" + r.stdout[-2000:] + r.stderr[-2000:])
    steps = read_frd(job + ".frd")
    rf = read_rf(job + ".dat")
    # nodes away from the support / load faces (the rigid fixing gives edge peaks there)
    Xn = {int(t): X[i] for i, t in enumerate(tags)}
    from scipy.spatial import cKDTree
    near = np.array([Xn[n] for n in sets["fixed"] + sets["load"]])
    tree = cKDTree(near)
    far_ids = [int(t) for t in tags if tree.query(Xn[int(t)])[0] > 2.0 * h]
    out = []
    for i, cs in enumerate(model["cases"]):
        S, U = steps[i]
        vm = {n: mises(s) for n, s in S.items()}
        vmax = max(vm.values())
        vfar = max(vm[n] for n in far_ids if n in vm)
        umax = max(np.linalg.norm(u) for u in U.values())
        out.append({"model": model["id"], "case": cs["name"], "nodes": len(tags), "elements": len(E), "h_mm": h,
                    "mises_max": vmax, "mises_far": vfar, "u_max": umax, "allow": cs["sigma_allow_MPa"],
                    "sf_req": cs["sf_required"], "rf": rf[i] if i < len(rf) else [np.nan] * 3,
                    "rf_exp": cs["reaction_F_N"]})
    return out


def mises(s):
    sx, sy, sz, txy, tyz, tzx = s
    return float(np.sqrt(0.5 * ((sx - sy) ** 2 + (sy - sz) ** 2 + (sz - sx) ** 2) + 3 * (txy ** 2 + tyz ** 2 + tzx ** 2)))


def read_frd(path):
    """[(stress {node: 6}, disp {node: 3})] per step, nodal values."""
    steps, cur, block = [], None, None
    for line in open(path, errors="replace"):
        if line.startswith("    1PSTEP"):
            pass
        if line.startswith(" -4"):
            name = line.split()[1]
            block = name
            if name == "DISP":
                cur = [{}, {}]
                steps.append(cur)
            continue
        if line.startswith(" -3"):
            block = None
            continue
        if block in ("DISP", "STRESS") and line.startswith(" -1"):
            n = int(line[3:13])
            vals = [float(line[13 + 12 * j:25 + 12 * j]) for j in range((len(line.rstrip()) - 13) // 12)]
            if block == "DISP":
                cur[1][n] = np.array(vals[:3])
            else:
                cur[0][n] = vals[:6]
    return [(s, u) for s, u in steps]


def read_rf(path):
    out, take = [], False
    for line in open(path, errors="replace"):
        if "total force" in line and "fixed" in line.lower():
            take = True
            continue
        if take and line.strip():
            out.append([float(v) for v in line.split()[:3]])
            take = False
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fea", default=os.path.join(ROOT, "fea", "RTC-7"))
    ap.add_argument("--only")
    ap.add_argument("--h-factor", type=float, default=1.0)
    a = ap.parse_args()
    cfg = json.load(open(os.path.join(a.fea, "rtc7_fea.json"), encoding="utf-8"))
    outdir = os.path.join(a.fea, "ccx")
    os.makedirs(outdir, exist_ok=True)
    rows = []
    prev = os.path.join(outdir, "summary.json")
    old = json.load(open(prev)) if os.path.isfile(prev) else []
    for m in cfg["models"]:
        if a.only and m["id"] not in a.only.split(","):
            rows += [r for r in old if r["model"] == m["id"]]
            continue
        res = run(m, cfg, outdir, a.h_factor)
        old = [r for r in old if r["model"] != m["id"]] + [dict(r, rf=list(map(float, r["rf"]))) for r in res]
        json.dump(old, open(prev, "w"), indent=1)
        for r in res:
            print(f"{r['model']:8s} {r['case']}: nodes {r['nodes']}, Mises max {r['mises_max']:6.1f} / away from "
                  f"supports {r['mises_far']:6.1f} MPa (allow {r['allow']:.0f}), u {r['u_max']:.3f} mm, "
                  f"RF {np.round(r['rf'], 0)} vs expected {np.round(r['rf_exp'], 0)}")
        rows += res
    Sy = cfg["material"]["Sy_MPa"]
    L = ["# RTC-7: предварительный расчёт прочности звеньев (CalculiX, до Ansys)", "",
         "Те же данные, что для Ansys (`rtc7_fea.json`, `geometry/*.step`): тетраэдры 2-го порядка, закрепление жёсткое, "
         "нагрузка через жёсткое тело в удалённой точке, поле ускорений детали. АМг6, σ0,2 = %.0f МПа." % Sy, "",
         "«Вдали от опор» — максимум по узлам дальше двух размеров элемента от граней закрепления и нагрузки "
         "(у кромок жёсткой заделки — концентрация, которой в болтовом стыке нет). Запас = σ0,2 / σэкв.", "",
         "| Звено | Случай | Узлов | σэкв max, МПа | σэкв вдали от опор, МПа | Запас (вдали) | Требуется | Перемещение max, мм | Реакция F, Н (расчёт / ожидаемая) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        sf = Sy / r["mises_far"]
        flag = "" if sf >= r["sf_req"] else " **— мало**"
        L.append(f"| {r['model']} | {r['case']} | {r['nodes']} | {r['mises_max']:.0f} | {r['mises_far']:.0f} | {sf:.2f}{flag} | "
                 f"{r['sf_req']:g} | {r['u_max']:.2f} | {fe.fmt3(r['rf'])} / {fe.fmt3(r['rf_exp'])} |")
    open(os.path.join(outdir, "summary.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    with open(os.path.join(outdir, "summary.csv"), "w", encoding="utf-8") as f:
        f.write("model;case;nodes;mises_max_MPa;mises_far_MPa;SF_far;SF_required;u_max_mm;RFx;RFy;RFz;RFx_exp;RFy_exp;RFz_exp\n")
        for r in rows:
            f.write(";".join([r["model"], r["case"], str(r["nodes"])] + [f"{v:.2f}" for v in
                    (r["mises_max"], r["mises_far"], Sy / r["mises_far"], r["sf_req"], r["u_max"], *r["rf"], *r["rf_exp"])]) + "\n")
    print("->", os.path.join(outdir, "summary.md"))


if __name__ == "__main__":
    main()
