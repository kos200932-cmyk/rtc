"""Full arm J1..J7 of the user's configuration (user's J1-J2, LINK-2B box, SHM-KB50F, v2 arm from J3 on):
ROBOTASM links-user/RTC-7-user-J1-J7.txt + preview.   python tools/gen_user_full.py <out.png>"""
import sys, os, re, math; sys.path.insert(0, os.path.dirname(__file__))
import numpy as np, gen_user_l123 as g
V2="robot/RTC-7-v2-J1-J7.txt"
comps={}; locks=[]
for ln in open(V2,encoding="utf-8"):
    t=ln.split()
    if t[:1]==["COMP"]:
        comps[t[1]]=(t[2],g.frame([float(v) for v in t[3:6]],[float(v) for v in t[6:9]],[float(v) for v in t[9:12]]),"rigid" in t)
    if t[:1]==["LOCK"]: locks.append(t)
M=g.J3@np.linalg.inv(comps["J3"][1])
dist=["L3","J4","L4","J5","L5","J6","L6","J7"]
if __name__=="__main__":
    base=open("links-user/RTC-7-user-J1-J4.txt",encoding="utf-8").read().replace("\r\n","\n")
    head,rest=base.split("# Degrees of freedom",1)
    head=re.sub(r"COMP L3 .*\nCOMP J4 .*\n","",head)
    head=head.replace("ROBOTASM RTC-7-user-J1-J4","ROBOTASM RTC-7-user-J1-J7").replace(
        "# J1..J4 of the user's arm","# FULL ARM J1..J7 of the user's configuration (J7 = SHM-KB17)").replace(
        "GENERATED by tools/gen_user_l123.py","GENERATED by tools/gen_user_full.py (J1..J4 as RTC-7-user-J1-J4, links 3-6 and J4..J7 from robot/RTC-7-v2-J1-J7.txt\n# keep their v2 relation to J3)")
    J7F="joints/SHM-KB17/SHM-KB17.txt"   # user 2026-10-24: J7 = KB17 (SHM-KB17, link interface = SHM-60, same joint frame)
    lines=[g.comp(n, J7F if n=="J7" else comps[n][0], M@comps[n][1], "rigid" if comps[n][2] else "") for n in dist]
    head=head.rstrip("\n")+"\n"+"\n".join(lines)+"\n\n"
    lk=[l for l in rest.split("\n") if l.startswith("LOCK") and not l.split()[1] in ("L3","J4")]
    # 2026-10-24: no LOCK of the ОПУ inner ring (it closed the only loop J1 output - YULA - ОПУ inner ring; flexible
    # sub-assemblies then reported errors in SW). The ОПУ stays fixed as a whole, YULA turns with the J1 output.
    lk=[l for l in lk if l.split()[1]!="OPU"]
    lk+=["LOCK %-4s %-26s %-4s %s"%(t[1],"DMRD-KB17-01_Housing" if t[1]=="J7" else t[2],t[3],t[4]) for t in locks if t[1] in dist]
    txt=head+"# Degrees of freedom: base plate, ОПУ outer ring and J1 housing fixed; YULA on the J1 output shaft, link 1 on YULA\n# (the ОПУ stays fixed as a whole: no loop), each joint housing on the link before it, each link on the output shaft of the joint before it.\n"+"\n".join(lk)+"\n"
    # models changed in the user's configuration: rebuilt on every run (macro v29 "rebuild"), the rest built when missing
    out=[]
    for l in txt.split("\n"):
        t=l.split()
        if t[:1]==["COMP"] and t[1] in ("L2","J3","J7"): l=l+" rebuild"
        out.append(l)
    txt="\n".join(out).replace("REBUILD no\n","REBUILD no      # yes - rebuild ALL models; COMP ... rebuild - only that one (macro v29)\n")
    open("links-user/RTC-7-user-J1-J7.txt","w",encoding="utf-8",newline="\r\n").write(txt)
    print(txt)

def preview(png):
    import glob, pyvista as pv, link_build as lb, joint_envelope as je
    from OCP.STEPControl import STEPControl_Reader
    from OCP.BRepBuilderAPI import BRepBuilderAPI_Transform
    from OCP.BRepAlgoAPI import BRepAlgoAPI_Common
    from OCP.gp import gp_Trsf
    pv.global_theme.allow_empty_mesh=True
    def mv(s,T):
        t=gp_Trsf(); t.SetValues(*[float(v) for v in T[:3,:].ravel()]); return BRepBuilderAPI_Transform(s,t,True).Shape()
    def load(f):
        r=STEPControl_Reader(); r.ReadFile(f); r.TransferRoots(); return r.OneShape()
    P=[]
    for f in glob.glob("links-user/LINK-1U/assembly-parts/*.step"):
        n=os.path.basename(f)[:-5]
        if n=="J1-J2" or not n.isascii() or n.startswith(("DMRD-80E","SHM-1000","AK80")): continue
        P.append((n,load(f),"user","J1"))
    T1=g.frame([171,16.5826773713467,83.3667488342793],[1,0,0],[0,0.195090322015843,0.980785280403287])
    P+= [("LINK-1U",mv(lb.build_part(lb.parse("links-user/LINK-1U/LINK-1U.txt")[0][0]),T1),"link","L1"),
         ("YULA",lb.build_part(lb.parse("links-user/YULA/YULA.txt")[0][0]),"yula","L1"),
         ("BASEPLATE",lb.build_part(lb.parse("links-user/BASEPLATE/BASEPLATE.txt")[0][0]),"base","B"),
         ("LINK-2B",mv(lb.build_part(lb.parse("links-user/LINK-2B/LINK-2B.txt")[0][0]),g.L2),"link2","L2")]
    for n in ("L3","L4","L5","L6"):
        P.append(("LINK-"+n[1],mv(lb.build_part(lb.parse(comps[n][0])[0][0]),M),"link3",n))
    _all=je.all_joints; kb17=dict(_all()["SHM-KB17"]); kb17["x_out"]=59.5   # placed by the SHM-60 joint frame (base x=6.5)
    je.all_joints=lambda: {**_all(), "SHM-KB50": _all()["SHM-KB50F"], "SHM-60": kb17}
    J2v2=comps["J2"][1]
    for nm,s,jn,kind in lb.envelope_solids("robot/RTC-7-layout-v2.txt",["J2","J3","J4","J5","J6","J7"]):
        if jn=="base": continue
        Tn=g.J2@np.linalg.inv(J2v2) if jn=="J2" else M
        P.append((nm,mv(s,Tn),kind,jn))
    order=["B","J1","L1","J2","L2","J3","L3","J4","L4","J5","L5","J6","L6","J7"]
    for i,a in enumerate(P):
        for b in P[i+1:]:
            ia,ib=order.index(a[3]),order.index(b[3])
            if abs(ia-ib)<=1 or a[3]==b[3] or max(ia,ib)<=order.index("J2"): continue
            v=lb.volume(BRepAlgoAPI_Common(a[1],b[1]).Shape())[0]
            if v>1: print("OVERLAP",a[0],b[0],round(v))
    def mesh(s):
        tri=np.array(lb.triangles(s,0.6)); pts=tri.reshape(-1,3)
        return pv.PolyData(pts,np.hstack([np.full((len(tri),1),3),np.arange(len(pts)).reshape(-1,3)]).ravel()).clean()
    C={"link":"#d49a90","link2":"#c9bfae","link3":"#e0b93c","yula":"#6fae5a","base":"#c8a0c8"}
    def col(n,k):
        if k in C: return C[k]
        if "Flange" in n: return "#2a5d9f"
        if "RU178G" in n: return "#9aa1a8"
        if "AK80" in n or k=="motor": return "#2f3338"
        if "OutputShaft" in n or k=="rot": return "#7fae6e"
        if k=="cover": return "#d5dade"
        return "#b8c2cc"
    Ms=[(mesh(s),col(n,k)) for n,s,k,_ in P]
    allp=np.vstack([m.points for m,_ in Ms]); print("height top x",round(allp[:,0].max(),1))
    pl=pv.Plotter(off_screen=True,window_size=(2400,1400),shape=(1,2))
    side=np.cross(g.XJ2,g.UP)
    for i,(cam,t) in enumerate((((-0.6,-1,0.7),"RTC-7 user configuration J1..J7, zero pose"),(tuple(side),"side view (across the J2 axis)"))):
        pl.subplot(0,i); pl.set_background("white")
        for m,c in Ms: pl.add_mesh(m,color=c,specular=0.25)
        pl.view_vector(cam,viewup=(1,0,0)); pl.reset_camera(); pl.camera.zoom(1.15); pl.add_text(t,font_size=11,color="black")
    pl.screenshot(png); print("->",png)
if __name__=="__main__" and len(sys.argv)>1: preview(sys.argv[1])
