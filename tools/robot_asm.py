#!/usr/bin/env python3
"""Spec of the arm assembly for SolidWorks (BuildFromSpec ROBOTASM) from the layout.

    python tools/robot_asm.py --upto 3 [--out robot/RTC-7-J1-J3.txt]

Every joint assembly (joint frame = reducer frame: X along the axis, output face at x_out) is placed
with its origin at  face - u * x_out  and its X along the output direction u (= -motor side).
The turn of a joint about its own axis is fixed by convention (the link holes are made for it):
  joint along world Z  -> joint Z along world +X,   joint along world X -> joint Z along world +Z.
Links (links/LINK-n) are built in the world frame -> placed at the origin.  ОПУ RU178G: X along +Z,
x = 0 on the base plane (z = -28), Z along +X (inner-ring hole at 0 deg -> +X).
"""
import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import joint_envelope as je  # noqa: E402
import robot_scheme as rs  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def fmt(v):
    return " ".join(f"{x + 0.0:g}" for x in np.round(v, 3))


def reducer_of(joint):
    import re as _re
    for raw in open(os.path.join(ROOT, "joints", joint, joint + ".txt"), encoding="utf-8"):
        t = _re.split(r"#", raw, maxsplit=1)[0].split()
        if len(t) >= 3 and t[0] == "USE" and t[1] == "reducer":
            return t[2]
    raise ValueError(joint)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--layout", default=os.path.join(ROOT, "robot", "RTC-7-layout.txt"))
    ap.add_argument("--upto", type=int, default=3, help="last joint to include (links up to it)")
    ap.add_argument("--out")
    a = ap.parse_args()
    lay = rs.read_layout(a.layout)
    env = je.all_joints()
    name = f"RTC-7-J1-J{a.upto}"
    L = [f"# Arm assembly J1..J{a.upto} at the zero pose - GENERATED by tools/robot_asm.py --upto {a.upto}",
         "# Run BuildFromSpec on this file: missing models are built first (joints, links, ОПУ),",
         "# then placed by their frames and fixed. REBUILD yes - rebuild them all.",
         f"ROBOTASM {name}", "REBUILD no", "",
         "#    name   file                                              origin (x y z)       X axis    Z axis",
         "COMP OPU    components/ISKRA/RU178G/RU178G-UU-CC0-P5.txt       0 0 -28   0 0 1   1 0 0"]
    locks = []
    prev_link = None
    for i, ax in enumerate(lay["axes"][:a.upto]):
        jn = ax["joint"].rstrip("m")
        e = env[jn]
        md = np.zeros(3)
        md["XYZ".index(ax["motor"][1])] = 1 if ax["motor"][0] == "+" else -1
        u = -md
        org = ax["face"] - u * e["x_out"]
        z = np.array([1.0, 0, 0]) if abs(u[2]) > 0.5 else np.array([0, 0, 1.0])
        L.append(f"COMP {ax['name']:<6} joints/{jn}/{jn}.txt{'':<{28 - 2 * len(jn)}} {fmt(org):<20} {fmt(u):<9} {fmt(z)}")
        red = reducer_of(jn)
        if i > 0 and prev_link:
            locks.append(f"LOCK {ax['name']:<4} {red}-01_Housing          {prev_link:<4} LINK-{i}-01_Weldment")
        prev_link = None
        if i + 1 < a.upto:
            n = i + 1
            p = os.path.join(ROOT, "links", f"LINK-{n}", f"LINK-{n}.txt")
            if os.path.isfile(p):
                L.append(f"COMP L{n:<5} links/LINK-{n}/LINK-{n}.txt                       0 0 0     1 0 0   0 0 1   rigid")
                locks.append(f"LOCK L{n:<3} LINK-{n}-01_Weldment         {ax['name']:<4} {red}-03_OutputShaft")
                prev_link = f"L{n}"
                if n == 1:
                    locks.append("LOCK OPU  RU178G-02_InnerRing          L1   LINK-1-01_Weldment   keep")
            else:
                L.append(f"# link {n} not designed yet")
    L += ["", "# Degrees of freedom: OPU (outer ring) and J1 (housing) fixed; every link is locked to the output",
          "# shaft of the joint before it, the next joint housing to the link. The joints are flexible",
          "# sub-assemblies: their output shafts turn about the joint axes -> J1, J2, J3 can be turned by",
          "# dragging (the input shafts / rotors turn independently - there is no gear mate)."] + locks
    out = a.out or os.path.join(ROOT, "robot", name + ".txt")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))
    print("->", out)


if __name__ == "__main__":
    main()
