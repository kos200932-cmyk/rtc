#!/usr/bin/env python3
"""Compact layout of the RTC-7 arm from the scheme topology and the real joint envelopes.

    python tools/robot_layout.py [--l3 1330] [--l5 1150] [--gap 10] [--plate 10] [--out robot/RTC-7-layout.txt]

Topology (from the user's scheme): J1 roll (vertical, motor down, on the ОПУ), J2 pitch (axis X,
motor -X), J3 roll, J4 pitch (motor +X), J5 roll, J6 pitch (motor -X), J7 roll (tool flange up).
Given: the link lengths J2->J4 (l3) and J4->J6 (l5) along Z. Everything else is minimised with the
envelopes of tools/joint_envelope.py (rear allowance 10 mm for the rear cover) and these rules:

  lateral (X) - the output face of every pitch joint is the plane that separates the two links:
    * the link on the output side (plate t on the output flange) carries the next roll joint whose
      column (radius R of that joint) starts right behind the plate: x_roll = x_face +- (t + R);
    * the link on the housing side keeps a gap g from the swept region of the output side:
      x_face = x_roll_prev -+ (R_prev + g)  -> the two roll columns are R_prev + R_next + t + g apart,
      so the pitch joint can fold the links past each other;
    * J2: its output face is put on the J1 axis (x = 0) as drawn; link 1 is a bracket on the -X side.
  vertical (Z):
    * J2 axis above the ОПУ face: J2 envelope radius + g (the J2 body rotates with J1 over the fixed
      base) and >= plate + g + R3 (the upper arm can swing to horizontal over link 1);
    * a roll joint after a pitch joint is moved down to the pitch axis as far as possible: its rear
      end (with the allowance) at the lower edge of the pitch joint output flange (z_pitch - R_out),
      and for J3 not lower than plate + g above the ОПУ face;
    * checks: the roll joint top stays below the next pitch joint body (z_next - R_next - g).
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import joint_envelope as je  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--l3", type=float, default=1330.0, help="J2 -> J4 along the arm, mm")
    ap.add_argument("--l5", type=float, default=1150.0, help="J4 -> J6 along the arm, mm")
    ap.add_argument("--gap", type=float, default=10.0)
    ap.add_argument("--plate", type=float, default=10.0)
    ap.add_argument("--out", default="robot/RTC-7-layout.txt")
    a = ap.parse_args()
    g, t = a.gap, a.plate
    env = je.all_joints()
    E2, E3, E4, E5, E6, E7 = (env[n] for n in ("SHM-1000", "SHM-500", "SHM-500", "SHM-150", "SHM-150", "SHM-60"))

    # ---- lateral
    xf2 = 0.0                                   # J2 output face on the J1 axis (as drawn)
    x3 = xf2 + t + E3["R"]                      # J3 column right behind the link-2 plate
    xf4 = x3 - E3["R"] - g                      # J4 output face (output -X)
    x5 = xf4 - t - E5["R"]
    xf6 = x5 + E5["R"] + g                      # J6 output face (output +X)
    x7 = xf6 + t + E7["R"]
    # ---- vertical
    z2 = max(E2["R"] + g, t + g + E3["R"])
    z3_rear = max(z2 - E2["R_out"], t + g)
    z3_face = z3_rear + E3["L"]
    z4 = z2 + a.l3
    z5_rear = z4 - E4["R_out"]
    z5_face = z5_rear + E5["L"]
    z6 = z4 + a.l5
    z7_rear = z6 - E6["R_out"]
    z7_face = z7_rear + E7["L"]
    checks = [("J3 top below the J4 body", z3_face, z4 - E4["R"] - g),
              ("J5 top below the J6 body", z5_face, z6 - E6["R"] - g)]
    bad = [c for c in checks if c[1] > c[2]]
    for name, v, lim in checks:
        print(f"{'OK ' if v <= lim else 'BAD'} {name}: {v:.1f} <= {lim:.1f}")

    L = []
    w = L.append
    w("# Kinematic layout of the arm - GENERATED by tools/robot_layout.py (do not edit by hand,")
    w(f"# change the rules / arguments there):  --l3 {a.l3:g} --l5 {a.l5:g} --gap {g:g} --plate {t:g}")
    w("# Topology from the user's scheme (2026-10-18, v2): rectangle = joint, hatched end = motor side,")
    w("# orange line = axis. Given: J2->J4 = l3, J4->J6 = l5. All other distances are minimised from the")
    w("# joint envelopes (tools/joint_envelope.py); J3 is moved down to J2 and J5 down to J4 as far as")
    w("# possible (rules in the header of tools/robot_layout.py).")
    w("ROBOT RTC-7")
    w("UNITS mm deg")
    w("# World frame = the X/Y frame of the scheme: origin on the J1 axis at the top face of the ОПУ,")
    w("# +Z up along J1, +X to the right (toward the J3 column), +Y = Z x X (into the scheme).")
    w("# AXIS name joint  point on the axis (x y z)  direction  motor/output side  face= output face centre")
    rows = [
        ("J1", "SHM-150m", (0, 0, 0), (0, 0, 1), "-Z", "+Z", None, "base turn: ОПУ RU178G + KB32 + RI80 (joint not designed yet)"),
        ("J2", "SHM-1000", (0, 0, z2), (1, 0, 0), "-X", "+X", (xf2, 0, z2), "shoulder; output face on the J1 axis"),
        ("J3", "SHM-500", (x3, 0, z2), (0, 0, 1), "-Z", "+Z", (x3, 0, z3_face), "upper-arm roll; rear end at the lower edge of the J2 output flange"),
        ("J4", "SHM-500", (x3, 0, z4), (1, 0, 0), "+X", "-X", (xf4, 0, z4), f"elbow; {a.l3:g} above J2"),
        ("J5", "SHM-150", (x5, 0, z4), (0, 0, 1), "-Z", "+Z", (x5, 0, z5_face), "forearm roll; rear end at the lower edge of the J4 output flange"),
        ("J6", "SHM-150", (x5, 0, z6), (1, 0, 0), "-X", "+X", (xf6, 0, z6), f"wrist; {a.l5:g} above J4"),
        ("J7", "SHM-60", (x7, 0, z6), (0, 0, 1), "-Z", "+Z", (x7, 0, z7_face), "flange roll; rear end at the lower edge of the J6 output flange"),
    ]
    f3 = lambda v: " ".join(f"{c:g}" if float(c).is_integer() else f"{c:.1f}" for c in v)
    for n, j, p, d, m, o, face, c in rows:
        fs = f"face={','.join(f'{v:.1f}' for v in face)}" if face else ""
        w(f"AXIS  {n}  {j:<9} {f3(p):<16} {f3(d):<7} motor={m} output={o} {fs:<28} # {c}")
    w("# Tool flange = output face of ШМ-60 (the tool is not on the scheme).")
    w(f"FLANGE {f3((x7, 0, z7_face))}   0 0 1")
    w("END")
    out = os.path.join(ROOT, a.out)
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nlateral offsets: J1->J3 {x3:.1f}, J3->J5 {x3 - x5:.1f}, J5->J7 {x7 - x5:.1f}; "
          f"ОПУ -> J2 {z2:.1f}; J6 -> flange {z7_face - z6:.1f}")
    if bad:
        sys.exit("layout check FAILED")


if __name__ == "__main__":
    main()
