#!/usr/bin/env python3
"""Loads of the joints of the user's arm (links-user/RTC-7-user-J1-J7.txt: J1-J2 of the user, box link 2, J3 SHM-KB50F,
links 3-6 of v2, J7 SHM-KB17, SZU gripper) + the kinematic layout file for the load scheme.

    python tools/user_loads.py [--poses 20000] [--payload 8] [--pay-off 200]
      -> robot/RTC-7-layout-user.txt (axes in the scheme frame), robot/RTC-7-loads-user.md / .json
    python tools/joint_load_scheme.py --layout robot/RTC-7-layout-user.txt --select robot/RTC-7-loads-user.json \
        --png robot/RTC-7-load-scheme-user.png --title "..."

Mass model (as tools/cart_reach.py): point masses at the centres of mass of the arm groups (geometry of the models),
masses MASS of cart_reach.py (links from the models, joints - load model estimates, SZU 4 kg); payload `--payload` kg
`--pay-off` mm beyond the TCP along the SZU axis (TCP = SZU end face, 150 mm from the J7 flange).
Loads per joint (as tools/layout_select.py): torque about the axis, tilting moment and axial / radial force at the
output face; worst over random poses in the joint ranges (J2 +-90 - mounting plane, J4 +-170, the others +-180),
gravity + all joints at +-0.2 rad/s and +-0.1 rad/s^2 (random signs, point masses, D'Alembert).
"""
import argparse, json, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = 9810.0                                       # mm/s^2
# reducers (components/DMRD/KB-series.txt) and motors (robot/RTC-7-loads-v2.json); J7 KB17 (user 2026-10-24)
RED = {"KB25": (62, 193.5, 5300, 93, 135), "80E": (1400, 2156, 0, 1960, 3920), "KB50": (415, 1032, 11200, 747, 1245),
       "KB45": (375, 740, 10200, 675, 1125), "KB32": (103, 336, 8800, 155, 240), "KB17": (23, 48, 2600, 35, 42)}
LINEUP = [("SHM-KB25", "KB25", "RI70-KV95", 0.94, 1, 79, 59.5), ("SHM-1000", "80E", "AK80-9-V3-KV100", 9.0, 9, 153, 149.0),
          ("SHM-KB50F", "KB50", "RI115-PH-KV40", 5.5, 1, 99, 118.0), ("SHM-KB45", "KB45", "RI115-PH-KV40", 5.5, 1, 79, 99.0),
          ("SHM-KB32", "KB32", "RI70-KV95", 0.94, 1, 79, 65.5), ("SHM-KB25", "KB25", "RI70-KV95", 0.94, 1, 49, 59.5),
          ("SHM-KB17", "KB17", "RI70-KV95", 0.94, 1, 21, 56.5)]
JMASS = [4.0, 25.1, 20.0, 15.0, 6.0, 3.5, 1.8]
RANGE = [180, 90, 180, 170, 180, 180, 180]


def frames():
    """joint origins (joint frame x = 0) and output directions in the arm frame (X = J1 up)."""
    argv = sys.argv; sys.argv = [argv[0]]
    try:
        import gen_user_full as gf, gen_user_l123 as g
    finally:
        sys.argv = argv
    T = [None] * 7
    T[0] = g.frame([-33.5, 0, 0], [1, 0, 0], [0, -0.5, 0.866025])
    T[1] = g.J2
    for k, n in enumerate(["J3", "J4", "J5", "J6", "J7"], 2):
        T[k] = gf.M @ gf.comps[n][1]
    return [(t[:3, 3].copy(), t[:3, 0].copy()) for t in T], g


def write_layout(path, ax, g, flange):
    ez = np.array([1.0, 0, 0]); ex = np.array(g.XJ2); ey = np.cross(ez, ex)
    R = lambda p: np.array([p @ ex, p @ ey, p @ ez])
    L = ["# Kinematic layout of the USER's arm (links-user/RTC-7-user-J1-J7.txt, 2026-10-27) - GENERATED by tools/user_loads.py",
         "# Scheme frame: origin on the J1 axis at the ОПУ base plane, +Z up along J1, +X along the J2 axis (outward),",
         "# +Y = Z x X. J1-J2 of the user, box link 2 (LINK-2B), J3 SHM-KB50F, links 3-6 of v2, J7 SHM-KB17, SZU gripper.",
         "ROBOT RTC-7-user", "UNITS mm deg"]
    for k, ((o, d), (jn, *_r, xo)) in enumerate(zip(ax, LINEUP)):
        po, dd = R(o), R(d)
        a = "XYZ"[int(np.argmax(abs(dd)))]; sg = "+" if dd[int(np.argmax(abs(dd)))] > 0 else "-"
        f = po + dd * xo
        L.append(f"AXIS  J{k + 1}  {jn:9s} {po[0]:.1f} {po[1]:.1f} {po[2]:.1f}   {dd[0]:.0f} {dd[1]:.0f} {dd[2]:.0f}   "
                 f"motor={'-' if sg == '+' else '+'}{a} output={sg}{a} face={f[0]:.1f},{f[1]:.1f},{f[2]:.1f}")
    fp = R(flange)
    L += [f"# Tool flange = output face of SHM-KB17 (the SZU gripper is not on the scheme, TCP 150 mm beyond).",
          f"FLANGE {fp[0]:.1f} {fp[1]:.1f} {fp[2]:.1f}   0 0 1", "END"]
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--poses", type=int, default=20000)
    ap.add_argument("--payload", type=float, default=8.0)
    ap.add_argument("--pay-off", type=float, default=200.0)
    ap.add_argument("--speed", type=float, default=0.2)
    ap.add_argument("--accel", type=float, default=0.1)
    ap.add_argument("--eta", type=float, default=0.8)
    a = ap.parse_args()
    import cart_reach as cr
    arm = cr.Arm(geometry=True)
    ax, g = frames()
    write_layout(os.path.join(ROOT, "robot", "RTC-7-layout-user.txt"), ax, g, ax[6][0] + ax[6][1] * 56.5)
    faces = [o + d * x[-1] for (o, d), x in zip(ax, LINEUP)]
    bodies = [(cr.MASS[gr], arm.com[gr], cr.NMOV[gr]) for gr in cr.MASS]
    pay = arm.tcp0 + a.pay_off * arm.app0
    bodies.append((a.payload, pay, 7))
    m = np.array([b[0] for b in bodies]); c0 = np.array([b[1] for b in bodies]); nm = np.array([b[2] for b in bodies])
    rng = np.random.default_rng(1)
    gvec = np.array([-G, 0, 0])
    W = np.zeros((7, 4)); Wq = [None] * 7; h = 0.01
    def pos(q):
        _, cum = arm.fk(q)
        P = np.array([(cum[n] @ np.r_[c, 1])[:3] for c, n in zip(c0, nm)])
        F = [((cum[k] @ np.r_[faces[k], 1])[:3], cum[k][:3, :3] @ ax[k][1]) for k in range(7)]
        return P, F
    for it in range(a.poses):
        q = np.radians(rng.uniform(-1, 1, 7) * RANGE)
        w = a.speed * rng.choice([-1, 1], 7); al = a.accel * rng.choice([-1, 1], 7)
        P0, F0 = pos(q); Pp, _ = pos(q + w * h + 0.5 * al * h * h); Pm, _ = pos(q - w * h + 0.5 * al * h * h)
        acc = (Pp - 2 * P0 + Pm) / (h * h)                        # mm/s^2
        f = m[:, None] * (gvec - acc)                             # load on the arm, N*... (kg mm/s^2 = mN)
        for k in range(7):
            sel = nm >= k + 1
            p, d = F0[k]
            Fk = f[sel].sum(0) / 1000.0                           # N
            Mk = np.cross(P0[sel] - p, f[sel]).sum(0) / 1e6       # N*m
            v = [abs(Fk @ d), np.linalg.norm(Fk - (Fk @ d) * d), np.linalg.norm(Mk - (Mk @ d) * d), abs(Mk @ d)]
            for j in range(4):
                if v[j] > W[k, j]:
                    W[k, j] = v[j]
    # W columns: Fa, Fr, tilt, torque
    rows = []; js = []
    for k, (jn, red, mo, mT, pre, i, xo) in enumerate(LINEUP):
        T, Mt, Fa, Tss, Tpk = RED[red]
        Tm = W[k, 3] / (i * a.eta); nmot = a.speed * i * 60 / (2 * math.pi)
        js.append({"joint": f"J{k + 1}", "reducer": {"name": red, "T": T, "Fa": Fa, "Mt": Mt, "Tpk": Tpk, "Tss": Tss},
                   "mass": JMASS[k], "torque": W[k, 3], "tilt": W[k, 2], "Fa": W[k, 0], "Fr": W[k, 1], "motor": mo,
                   "motor_T": mT, "pre": pre, "ratio": i, "Tm": Tm, "n_motor": nmot})
        pct = lambda v, lim: f"{v:.0f} ({lim:.0f}, {100 * v / lim:.0f} %)" if lim else f"{v:.0f} (-)"
        rows.append(f"| J{k + 1} | {red} | {JMASS[k]:.1f} | {pct(W[k, 3], T)} | "
                    f"{pct(W[k, 2], Mt) if k else f'{W[k, 2]:.0f} (ОПУ)'} | {pct(W[k, 0], Fa) if k else f'{W[k, 0]:.0f} (ОПУ)'} | "
                    f"{W[k, 1]:.0f} | {mo} | {i} | {Tm:.2f} ({mT:g}) |")
    C0, Dp = 135e3, 0.178
    P0 = W[0, 1] + 2 * W[0, 2] / Dp + 0.44 * W[0, 0]
    mov = sum(cr.MASS.values())
    md = [f"# RTC-7 user configuration: joint loads (`python tools/user_loads.py`), 2026-10-27", "",
          f"Payload {a.payload:g} kg {a.pay_off:g} mm beyond the TCP (SZU end face) + SZU 4 kg; all joints at ±{a.speed:g} rad/s, "
          f"±{a.accel:g} rad/s²; worst of {a.poses} random poses (J2 ±90°, J4 ±170°, others ±180°). Moving mass "
          f"(without payload, on the ОПУ): {mov:.1f} kg.", "",
          "| Joint | Reducer | Joint mass, kg | Torque, N·m (rated) | Tilting, N·m (allow.) | Axial, N (allow.) | Radial, N | Motor | Ratio | Motor torque, N·m (rated) |",
          "|---|---|---|---|---|---|---|---|---|---|"] + rows + ["",
          f"J1 ОПУ RU178G: P0 = Fr + 2M/Dp + 0.44 Fa = {P0 / 1e3:.1f} kN against C0 135 kN (s0 = {C0 / P0:.1f})."]
    open(os.path.join(ROOT, "robot", "RTC-7-loads-user.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    gg = lambda v: f"{v:g}".replace(".", ",")
    sub1 = (f"Груз {gg(a.payload)} кг в {gg(a.pay_off)} мм за TCP (торец СЗУ) + СЗУ 4 кг; все шарниры ±{gg(a.speed)} рад/с, "
            f"±{gg(a.accel)} рад/с²; худшая из {a.poses} поз (J2 ±90°, J4 ±170°, остальные ±180°); подвижная масса {mov:.0f} кг.")
    sub2 = ("Массы звеньев — по моделям, шарниров — оценка (у номера). Силы и опрокидывающий момент — на торце выходного вала. "
            "Двигатель: требуемый момент = M / (i · 0,8) против номинального.")
    json.dump({"payload": a.payload, "pay_off": a.pay_off, "speed": a.speed, "accel": a.accel, "reach": 0, "interface": 4.0,
               "share": 0.6, "sub1": sub1, "sub2": sub2, "joints": js, "P0": P0, "moving_mass": mov}, open(os.path.join(ROOT, "robot", "RTC-7-loads-user.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1, default=float)
    print("\n".join(md))


if __name__ == "__main__":
    main()
